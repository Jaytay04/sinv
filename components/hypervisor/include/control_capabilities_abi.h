#ifndef HYPERSINV_CONTROL_CAPABILITIES_ABI_H
#define HYPERSINV_CONTROL_CAPABILITIES_ABI_H

#include <stddef.h>
#include <stdint.h>

#define HYPERVISOR_CONTROL_CAPABILITIES_VERSION UINT32_C(1)
#define HYPERVISOR_CONTROL_CAPABILITIES_REQUEST_SIZE UINT32_C(16)
#define HYPERVISOR_CONTROL_CAPABILITIES_RESPONSE_SIZE UINT32_C(32)
#define HYPERVISOR_CONTROL_CAPABILITIES_FLAGS_NONE UINT32_C(0)
#define HYPERVISOR_CONTROL_CAPABILITIES_STATUS_SUCCESS UINT32_C(0)

#define HYPERVISOR_CONTROL_CAPABILITY_PERSISTENT_RUNTIME (UINT64_C(1) << 0)
#define HYPERVISOR_CONTROL_CAPABILITY_EPT_DIAGNOSTICS (UINT64_C(1) << 1)
#define HYPERVISOR_CONTROL_CAPABILITY_VPID_STATUS (UINT64_C(1) << 2)
#define HYPERVISOR_CONTROL_CAPABILITY_VMEXIT_TELEMETRY (UINT64_C(1) << 3)
#define HYPERVISOR_CONTROL_CAPABILITY_DISPATCH_STATUS (UINT64_C(1) << 4)
#define HYPERVISOR_CONTROL_CAPABILITY_COHERENT_OBSERVATION (UINT64_C(1) << 5)
#define HYPERVISOR_CONTROL_CAPABILITY_PROCESS_TARGET_PID (UINT64_C(1) << 6)
#define HYPERVISOR_CONTROL_CAPABILITY_PROCESS_TARGET_RELEASE (UINT64_C(1) << 7)
#define HYPERVISOR_CONTROL_CAPABILITY_PROCESS_TARGET_MATCHED_RELEASE (UINT64_C(1) << 8)
#define HYPERVISOR_CONTROL_CAPABILITY_PROCESS_TARGET_SESSION_OWNER (UINT64_C(1) << 9)
#define HYPERVISOR_CONTROL_CAPABILITY_HLT_EXIT_DIAGNOSTIC (UINT64_C(1) << 10)

#define HYPERVISOR_CONTROL_CAPABILITIES_ALL UINT64_C(0x00000000000007FF)
#define HYPERVISOR_CONTROL_OPERATIONAL_IOCTL_COUNT UINT32_C(30)

typedef struct HYPERVISOR_CONTROL_CAPABILITIES_REQUEST {
    uint32_t Version;
    uint32_t Size;
    uint32_t Flags;
    uint32_t Reserved;
} HYPERVISOR_CONTROL_CAPABILITIES_REQUEST;

typedef struct HYPERVISOR_CONTROL_CAPABILITIES_RESPONSE {
    uint32_t Version;
    uint32_t Size;
    uint32_t Status;
    uint32_t Flags;
    uint64_t CapabilityBits;
    uint32_t OperationalIoctlCount;
    uint32_t Reserved;
} HYPERVISOR_CONTROL_CAPABILITIES_RESPONSE;

#if defined(__cplusplus)
#define HYPERSINV_CAPABILITIES_ASSERT static_assert
#else
#define HYPERSINV_CAPABILITIES_ASSERT _Static_assert
#endif

HYPERSINV_CAPABILITIES_ASSERT(
    sizeof(HYPERVISOR_CONTROL_CAPABILITIES_REQUEST) == 16,
    "control capabilities request ABI");
HYPERSINV_CAPABILITIES_ASSERT(
    sizeof(HYPERVISOR_CONTROL_CAPABILITIES_RESPONSE) == 32,
    "control capabilities response ABI");
HYPERSINV_CAPABILITIES_ASSERT(
    offsetof(HYPERVISOR_CONTROL_CAPABILITIES_RESPONSE, CapabilityBits) == 16,
    "control capabilities bitmap offset");
HYPERSINV_CAPABILITIES_ASSERT(
    offsetof(HYPERVISOR_CONTROL_CAPABILITIES_RESPONSE,
        OperationalIoctlCount) == 24,
    "control capabilities count offset");

#undef HYPERSINV_CAPABILITIES_ASSERT

#endif /* HYPERSINV_CONTROL_CAPABILITIES_ABI_H */
