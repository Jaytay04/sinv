/*
 * V3D1 private persistent launch ABI.
 *
 * This is a private C/MASM contract for the opaque LaunchStorage owned by
 * V3C.  It deliberately shares no types or macros with the transient launch ABI.
 * Numeric offsets are part of the ABI: future MASM must consume these names
 * rather than infer a layout.  C validates Magic/Version/Size and every
 * pointer/stack invariant before assembly writes any field.  A valid READY
 * exit returns RESIDENT without VMXOFF; native teardown is permitted only
 * after a validated SHUTDOWN exit and recorded shutdown proof.
 */

