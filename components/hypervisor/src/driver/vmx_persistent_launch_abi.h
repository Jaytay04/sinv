static inline int VmxV3dDiagnosticStateIsArmed(uint32_t state)
{
    return state >= VMX_V3D_DIAGNOSTIC_FIRST_ARMED &&
        state <= VMX_V3D_DIAGNOSTIC_LAST_ARMED &&
        (state & VMX_V3D_DIAGNOSTIC_STATE_PARITY_MASK) != 0;
}

static inline int VmxV3dDiagnosticStateIsComplete(uint32_t state)
{
    return state >= VMX_V3D_DIAGNOSTIC_FIRST_COMPLETE &&
        state <= VMX_V3D_DIAGNOSTIC_LAST_COMPLETE &&
        (state & VMX_V3D_DIAGNOSTIC_STATE_PARITY_MASK) == 0;
}

static inline int VmxV3dDiagnosticStateContractValid(uint32_t state,
                                                     uint32_t contract)
{
    return contract == ~state;
}

static inline int VmxV3dDiagnosticStatePairValid(uint32_t armed_state,
                                                 uint32_t complete_state)
{
    return VmxV3dDiagnosticStateIsArmed(armed_state) &&
        VmxV3dDiagnosticStateIsComplete(complete_state) &&
        complete_state == armed_state + 1u;
}

