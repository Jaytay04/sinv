/* The WDK adapter statically pins these private values to authoritative
 * driver-owner and EPT lifecycle definitions. */
typedef enum VMX_EPT_PERSISTENT_STATUS_RUNTIME_PHASE {
    VMX_EPT_PERSISTENT_STATUS_PHASE_UNINITIALIZED = 0,
    VMX_EPT_PERSISTENT_STATUS_PHASE_DETACHED = 1,
    VMX_EPT_PERSISTENT_STATUS_PHASE_ATTACHING = 2,
    VMX_EPT_PERSISTENT_STATUS_PHASE_ATTACHED = 3,
    VMX_EPT_PERSISTENT_STATUS_PHASE_TEARDOWN_PENDING = 4
} VMX_EPT_PERSISTENT_STATUS_RUNTIME_PHASE;

typedef enum VMX_EPT_PERSISTENT_STATUS_EPT_STAGE {
    VMX_EPT_PERSISTENT_STATUS_STAGE_ZERO = 0,
    VMX_EPT_PERSISTENT_STATUS_STAGE_READY = 1,
    VMX_EPT_PERSISTENT_STATUS_STAGE_SESSION_ONLY = 2,
    VMX_EPT_PERSISTENT_STATUS_STAGE_COMPOSITION_GONE = 3,
    VMX_EPT_PERSISTENT_STATUS_STAGE_BLOCKED = 4
} VMX_EPT_PERSISTENT_STATUS_EPT_STAGE;

typedef HYPERVISOR_EPT_STATUS_START_EVIDENCE
    VMX_EPT_PERSISTENT_STATUS_START_EVIDENCE;
