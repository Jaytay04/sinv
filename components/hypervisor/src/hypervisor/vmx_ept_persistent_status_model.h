typedef struct VMX_EPT_PERSISTENT_STATUS_VIEW {
    uint32_t Version, Size, Reserved[2];
    int32_t PhaseQueryStatus, EptValidateStatus;
    uint32_t RuntimePhase, EptStage, EptZero;
    uint32_t StartEvidenceValid, DestroyEvidenceValid, ReservedState;
    VMX_EPT_PERSISTENT_STATUS_START_EVIDENCE Start;
    VMX_EPT_PERSISTENT_STATUS_DESTROY_EVIDENCE Destroy;
} VMX_EPT_PERSISTENT_STATUS_VIEW;

/* View and output must be disjoint; output must be zero. Invalid structural
 * input preserves output. Runtime/EPT contradictions publish MALFORMED. */
int VmxEptPersistentStatusModelProject(
    const VMX_EPT_PERSISTENT_STATUS_VIEW* view,
    VMX_EPT_PERSISTENT_STATUS_RECORD* output);

